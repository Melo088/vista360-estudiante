CREATE TABLE auditoria_acceso (
    id                     NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY,
    ocurrido_en            TIMESTAMP     NOT NULL,
    sujeto_id              VARCHAR2(50)  NOT NULL,
    sujeto_tipo            VARCHAR2(20)  NOT NULL,
    rol                    VARCHAR2(30)  NOT NULL,
    estudiante_consultado  VARCHAR2(9),
    recurso                VARCHAR2(200) NOT NULL,
    operacion              VARCHAR2(10)  NOT NULL,
    resultado              VARCHAR2(20)  NOT NULL,
    direccion_ip           VARCHAR2(45),
    agente_usuario         VARCHAR2(300),
    correlacion_id         VARCHAR2(64)  NOT NULL,
    CONSTRAINT pk_auditoria PRIMARY KEY (id),
    CONSTRAINT ck_auditoria_sujeto CHECK (sujeto_tipo IN ('PERSONA', 'SERVICIO')),
    CONSTRAINT ck_auditoria_resultado CHECK (resultado IN ('PERMITIDO', 'DENEGADO'))
);
COMMENT ON TABLE auditoria_acceso IS 'Quien consulto que, cuando y desde donde. Escenario 4B. Registra tambien los accesos denegados, porque un intento rechazado es parte de la respuesta. correlacion_id enlaza la consulta con toda la cadena de servicios (S-10).';

CREATE TABLE marca_agua_sondeo (
    fuente             VARCHAR2(30)  NOT NULL,
    entidad            VARCHAR2(40)  NOT NULL,
    ultimo_corte       TIMESTAMP     NOT NULL,
    ultima_ejecucion   TIMESTAMP,
    registros_leidos   NUMBER(10),
    estado             VARCHAR2(20)  NOT NULL,
    ultimo_error       VARCHAR2(500),
    CONSTRAINT pk_marca_agua PRIMARY KEY (fuente, entidad),
    CONSTRAINT ck_marca_agua_fuente CHECK (fuente IN ('ERP', 'LMS')),
    CONSTRAINT ck_marca_agua_estado CHECK (estado IN ('OK', 'DEGRADADO', 'FALLIDO'))
);
COMMENT ON TABLE marca_agua_sondeo IS 'Hasta que momento se leyo cada entidad de cada fuente (S-02). 4A';
